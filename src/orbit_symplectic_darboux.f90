module orbit_symplectic_darboux
    !> Gauss collocation (midpoint = Gauss-1) in the global Darboux chart
    !> (X, Y, phi, p_phi) of the guiding-centre phase space, selected with
    !> canonical_chart = 'cartesian'.
    !>
    !> SIMPLE's canonical pairs are (theta, p_theta) and (phi, p_phi), and
    !> p_theta ~ s near the magnetic axis. With J = sigma p_theta and the
    !> field point u = (x, y) = sqrt(s) (cos, sin) theta,
    !>     X = sqrt(2 kappa) x,   Y = sigma sqrt(2 kappa) y,   kappa = J/s,
    !> one has X**2 + Y**2 = 2 J and dX ^ dY = dp_theta ^ dtheta, so one chart
    !> covers the axis X = Y = 0. kappa is regular and positive when the
    !> field is regular in u (libneo boozer_regular, or the analytic test
    !> field) and sigma = sign(p_theta/s). The step solves the s-stage Gauss
    !> system for the stage points W_i together with their field points U_i,
    !> constrained by the chart map C(U_i, phi_i, p_phi,i) = (X_i, Y_i), so
    !> the map is the symplectic Gauss map of dw/dt = J grad K(w). There is
    !> no radius floor, axis reflection, chart handoff or recovery path.
    !>
    !> The pointwise mathematics (q = h/s jets, kappa, H, the chart map, the
    !> vector field and the stage Jacobian blocks) is generated by
    !> gen/gen_darboux_chart.f90. Newton's first iteration uses the second
    !> field jets (mode 2); the chord iterations, the endpoint and the
    !> vector field use first jets (mode 1). Linear solves use the pivoted
    !> LU of orbit_rk_core.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use util, only: pi, twopi
    use field_can_base, only: field_can_t
    use field_can_boozer, only: evaluate_boozer_regular
    use field_can_test, only: evaluate_test_regular
    use boozer_regular, only: regular_field_t
    use orbit_symplectic_base, only: symplectic_integrator_t, sympl_rmax, &
        coeff_rk_gauss, SYMPLECTIC_STEP_OK, SYMPLECTIC_STEP_OUTSIDE_DOMAIN, &
        SYMPLECTIC_STEP_MAXITER, SYMPLECTIC_STEP_LINEAR_SOLVE
    use orbit_rk_core, only: rk_solve, rk_lu_factor, rk_lu_solve
    use finite_check, only: is_finite

    implicit none
    private

    public :: DARBOUX_FIELD_NONE, DARBOUX_FIELD_TEST, DARBOUX_FIELD_BOOZER
    public :: darboux_configure, darboux_enabled, darboux_stages
    public :: orbit_timestep_sympl_darboux, darboux_encode, darboux_advance
    public :: darboux_point_eval, darboux_stage_eval, darboux_field_point
    public :: darboux_field_values
    public :: darboux_stats_t, darboux_stats, darboux_stats_reset

    integer, parameter :: DARBOUX_FIELD_NONE = 0
    integer, parameter :: DARBOUX_FIELD_TEST = 1
    integer, parameter :: DARBOUX_FIELD_BOOZER = 2
    integer, parameter :: MAX_STAGES = 4
    integer, parameter :: MAX_UNKNOWNS = 6*MAX_STAGES
    integer, parameter :: MAXIT_STAGE = 32
    integer, parameter :: MAXIT_ENDPOINT = 16
    !> u with s below this is evaluated at the nearest representable point
    !> (s_min, 0): q = h/s needs s > 0. A representability guard at
    !> rho = 1e-100, not a physical floor; the resulting change in kappa is
    !> O(1e-100).
    real(dp), parameter :: S_REPRESENTABLE = 1.0e-200_dp

    !> Selected once, before tracing, by darboux_configure.
    integer :: darboux_field = DARBOUX_FIELD_NONE
    integer :: darboux_stages = 1
    !> Integrator radius r(s): s for Boozer, sqrt(s) for the test field.
    logical :: radius_is_rho = .false.
    real(dp) :: gauss_a(MAX_STAGES, MAX_STAGES) = 0.0_dp
    real(dp) :: gauss_c(MAX_STAGES) = 0.0_dp
    !> End-point weights d = b^T A^-1: w1 = w0 + sum_i d_i (W_i - w0).
    real(dp) :: gauss_d(MAX_STAGES) = 0.0_dp

    type :: darboux_stats_t
        integer(8) :: steps = 0
        integer(8) :: newton_iterations = 0
        integer(8) :: endpoint_iterations = 0
        integer(8) :: encodes = 0
        integer(8) :: failures = 0
        integer :: max_newton_iterations = 0
    end type darboux_stats_t

    type(darboux_stats_t) :: darboux_stats
    !$omp threadprivate(darboux_stats)

contains

    subroutine darboux_configure(field, stages)
        !> Select the field source and the number of Gauss stages (midpoint
        !> and Gauss-1 are s = 1). Called before tracing, outside threads.
        integer, intent(in) :: field, stages
        real(dp), allocatable :: a(:, :), b(:), c(:), at(:, :)
        integer :: info

        if (stages < 1 .or. stages > MAX_STAGES) &
            error stop 'darboux_configure: stages must be 1 to 4'
        darboux_field = field
        darboux_stages = stages
        radius_is_rho = field == DARBOUX_FIELD_TEST
        allocate (a(stages, stages), b(stages), c(stages))
        call coeff_rk_gauss(stages, a, b, c)
        gauss_a = 0.0_dp
        gauss_c = 0.0_dp
        gauss_d = 0.0_dp
        gauss_a(1:stages, 1:stages) = a
        gauss_c(1:stages) = c
        at = transpose(a)
        gauss_d(1:stages) = b
        call rk_solve(stages, at, gauss_d(1:stages), info)
        if (info /= 0) error stop 'darboux_configure: singular Gauss matrix'
    end subroutine darboux_configure

    logical function darboux_enabled()
        darboux_enabled = darboux_field /= DARBOUX_FIELD_NONE
    end function darboux_enabled

    subroutine darboux_stats_reset()
        darboux_stats = darboux_stats_t()
    end subroutine darboux_stats_reset

    pure real(dp) function s_from_radius(r)
        real(dp), intent(in) :: r

        if (radius_is_rho) then
            s_from_radius = r*r
        else
            s_from_radius = r
        end if
    end function s_from_radius

    pure real(dp) function radius_from_s(s)
        real(dp), intent(in) :: s

        if (radius_is_rho) then
            radius_from_s = sqrt(s)
        else
            radius_from_s = s
        end if
    end function radius_from_s

    subroutine regular_eval(x, y, phi, mode, rf)
        real(dp), intent(in) :: x, y, phi
        integer, intent(in) :: mode
        type(regular_field_t), intent(inout) :: rf

        select case (darboux_field)
        case (DARBOUX_FIELD_BOOZER)
            call evaluate_boozer_regular(x, y, phi, mode, rf)
        case (DARBOUX_FIELD_TEST)
            call evaluate_test_regular(x, y, mode, rf)
        case default
            error stop 'orbit_symplectic_darboux: no regular field selected'
        end select
    end subroutine regular_eval

    pure subroutine field_point(u, ue)
        !> The point at which the field is evaluated for field point u.
        real(dp), intent(in) :: u(2)
        real(dp), intent(out) :: ue(2)

        ue = u
        if (u(1)*u(1) + u(2)*u(2) < S_REPRESENTABLE) &
            ue = [sqrt(S_REPRESENTABLE), 0.0_dp]
    end subroutine field_point

    subroutine darboux_field_point(u, phi, mode, rf, qa, qh)
        !> Regular field at u and the jets of q_A = A_theta/s, q_h =
        !> h_theta/s (4 entries for mode 1, 10 for mode 2).
        real(dp), intent(in) :: u(2), phi
        integer, intent(in) :: mode
        type(regular_field_t), intent(inout) :: rf
        real(dp), intent(out) :: qa(10), qh(10)
        real(dp) :: ue(2), h(10)

        call field_point(u, ue)
        call regular_eval(ue(1), ue(2), phi, mode, rf)
        if (mode >= 2) then
            h = [rf%Ath, rf%dAth, rf%d2Ath]
            call darboux_quotient_d2(ue(1), ue(2), h, qa)
            h = [rf%hth, rf%dhth, rf%d2hth]
            call darboux_quotient_d2(ue(1), ue(2), h, qh)
        else
            h(1:4) = [rf%Ath, rf%dAth]
            call darboux_quotient_d1(ue(1), ue(2), h(1:4), qa(1:4))
            h(1:4) = [rf%hth, rf%dhth]
            call darboux_quotient_d1(ue(1), ue(2), h(1:4), qh(1:4))
        end if
    end subroutine darboux_field_point

    subroutine darboux_point_eval(u, phi, pphi, sigma, mu, ro0, rf, kappa, pth, &
                                  ham, vpar, chart, rhs, gu, udot)
        !> First jets at field point u: kappa = J/s, p_theta, H, v_par, the
        !> chart map C(u), the vector field, G = dC/du and du/dt.
        real(dp), intent(in) :: u(2), phi, pphi, sigma, mu, ro0
        type(regular_field_t), intent(inout) :: rf
        real(dp), intent(out) :: kappa, pth, ham, vpar, chart(2), rhs(4), &
            gu(2, 2), udot(2)
        real(dp) :: qa(10), qh(10)

        call darboux_field_point(u, phi, 1, rf, qa, qh)
        call point_from_jets(u, pphi, sigma, mu, ro0, rf, qa, qh, kappa, pth, &
                             ham, vpar, chart, rhs, gu, udot)
    end subroutine darboux_point_eval

    subroutine point_from_jets(u, pphi, sigma, mu, ro0, rf, qa, qh, kappa, pth, &
                               ham, vpar, chart, rhs, gu, udot)
        real(dp), intent(in) :: u(2), pphi, sigma, mu, ro0
        type(regular_field_t), intent(in) :: rf
        real(dp), intent(in) :: qa(10), qh(10)
        real(dp), intent(out) :: kappa, pth, ham, vpar, chart(2), rhs(4), &
            gu(2, 2), udot(2)
        real(dp) :: ue(2)

        call field_point(u, ue)
        call darboux_point(ue(1), ue(2), pphi, ro0, mu, sigma, qa(1:4), qh(1:4), &
                           [rf%Aph, rf%dAph], [rf%hph, rf%dhph], &
                           [rf%Bmod, rf%dBmod], kappa, pth, ham, vpar, chart, &
                           rhs, gu, udot)
    end subroutine point_from_jets

    subroutine darboux_stage_eval(u, phi, pphi, sigma, mu, ro0, chart, rhs, fu, &
                                  fw, gu, gw)
        !> Second jets at field point u: the chart map, the vector field and
        !> their derivatives with respect to u and (phi, p_phi).
        real(dp), intent(in) :: u(2), phi, pphi, sigma, mu, ro0
        real(dp), intent(out) :: chart(2), rhs(4), fu(4, 2), fw(4, 2), gu(2, 2), &
            gw(2, 2)
        type(regular_field_t) :: rf
        real(dp) :: qa(10), qh(10), ue(2)

        call darboux_field_point(u, phi, 2, rf, qa, qh)
        call field_point(u, ue)
        call darboux_stage(ue(1), ue(2), pphi, ro0, mu, sigma, qa, qh, &
                           [rf%Aph, rf%dAph, rf%d2Aph], &
                           [rf%hph, rf%dhph, rf%d2hph], &
                           [rf%Bmod, rf%dBmod, rf%d2Bmod], chart, rhs, fu, fw, &
                           gu, gw)
    end subroutine darboux_stage_eval

    subroutine darboux_field_values(r, theta, phi, f)
        !> Replace the field values in f by the regular field at the
        !> integrator point (r, theta, phi), so that start states, reseeds and
        !> collision kicks use the Hamiltonian the chart integrates.
        real(dp), intent(in) :: r, theta, phi
        type(field_can_t), intent(inout) :: f
        type(regular_field_t) :: rf
        real(dp) :: rho, ue(2)

        rho = sqrt(max(s_from_radius(r), 0.0_dp))
        call field_point(rho*[cos(theta), sin(theta)], ue)
        call regular_eval(ue(1), ue(2), phi, 0, rf)
        f%Ath = rf%Ath
        f%Aph = rf%Aph
        f%hth = rf%hth
        f%hph = rf%hph
        f%Bmod = rf%Bmod
    end subroutine darboux_field_values

    subroutine darboux_encode(si, f, status)
        !> Darboux state of the phase point (si%z, f%mu): field point from
        !> (r, theta), sigma = sign(p_theta/s), w = (C(u), phi, p_phi).
        type(symplectic_integrator_t), intent(inout) :: si
        type(field_can_t), intent(inout) :: f
        integer, intent(out) :: status
        type(regular_field_t) :: rf
        real(dp) :: u(2), rho, kappa, pth, ham, vpar, chart(2), rhs(4), gu(2, 2), &
            udot(2), qa(10), qh(10)

        status = SYMPLECTIC_STEP_OK
        rho = sqrt(max(s_from_radius(si%z(1)), 0.0_dp))
        u = rho*[cos(si%z(2)), sin(si%z(2))]
        call darboux_field_point(u, si%z(3), 1, rf, qa, qh)
        call point_from_jets(u, si%z(4), 1.0_dp, f%mu, f%ro0, rf, qa, qh, kappa, &
                             pth, ham, vpar, chart, rhs, gu, udot)
        if (.not. (abs(kappa) > 0.0_dp)) then
            status = SYMPLECTIC_STEP_LINEAR_SOLVE
            return
        end if
        si%chart_sigma = sign(1.0_dp, kappa)
        if (si%chart_sigma < 0.0_dp) &
            call point_from_jets(u, si%z(4), si%chart_sigma, f%mu, f%ro0, rf, qa, &
                                 qh, kappa, pth, ham, vpar, chart, rhs, gu, udot)
        if (.not. all(is_finite([chart, rhs, udot]))) then
            status = SYMPLECTIC_STEP_LINEAR_SOLVE
            return
        end if
        si%chart_w = [chart, si%z(3), si%z(4)]
        si%chart_u = u
        si%chart_rhs = rhs
        si%chart_udot = udot
        si%chart_kappa = kappa
        si%chart_mu = f%mu
        si%chart_z = si%z
        si%chart_valid = .true.
        darboux_stats%encodes = darboux_stats%encodes + 1
    end subroutine darboux_encode

    subroutine darboux_advance(w0, u0, rhs0, udot0, sigma, mu, ro0, h, rtol, &
                               xy_ref, w1, u1, rhs1, udot1, rf, kappa1, ham1, &
                               vpar1, status)
        !> One s-stage Gauss step of length h from w0 (field point u0, vector
        !> field rhs0 and du/dt udot0 at w0). Returns the end state with its
        !> field point, vector field, field values, kappa, H and v_par.
        !> Unknowns per stage: W_i (4) then U_i (2). Stage residual
        !>   W_i - w0 - h sum_j a_ij F(U_j, W_j),   C(U_i, W_i) - (X_i, Y_i).
        real(dp), intent(in) :: w0(4), u0(2), rhs0(4), udot0(2), sigma, mu, ro0
        real(dp), intent(in) :: h, rtol, xy_ref
        real(dp), intent(out) :: w1(4), u1(2), rhs1(4), udot1(2), kappa1, ham1, &
            vpar1
        type(regular_field_t), intent(inout) :: rf
        integer, intent(out) :: status

        real(dp) :: z(MAX_UNKNOWNS), res(MAX_UNKNOWNS), jac(MAX_UNKNOWNS**2)
        real(dp) :: tolref(MAX_UNKNOWNS)
        real(dp) :: chart(2, MAX_STAGES), rhs(4, MAX_STAGES), fu(4, 2, MAX_STAGES)
        real(dp) :: fw(4, 2, MAX_STAGES), gu(2, 2, MAX_STAGES), gw(2, 2, MAX_STAGES)
        real(dp) :: pth, g2(2, 2), r2(2), s_max
        integer :: ipiv(MAX_UNKNOWNS), ns, n, i, j, k, it, info, o
        logical :: converged

        status = SYMPLECTIC_STEP_OK
        ns = darboux_stages
        n = 6*ns
        ! Iterates may leave the domain transiently (the field extends
        ! smoothly); only a wild excursion is rejected here. The domain test
        ! that locates the boundary event applies to the converged end point.
        s_max = 4.0_dp*s_from_radius(sympl_rmax)

        do i = 1, ns
            o = 6*(i - 1)
            z(o + 1:o + 4) = w0 + h*gauss_c(i)*rhs0
            z(o + 5:o + 6) = u0 + h*gauss_c(i)*udot0
            tolref(o + 1:o + 2) = xy_ref
            tolref(o + 3) = 1.0_dp
            tolref(o + 4) = max(abs(w0(4)), 1.0_dp)
            tolref(o + 5:o + 6) = 1.0_dp
        end do

        converged = .false.
        do it = 1, MAXIT_STAGE
            do i = 1, ns
                o = 6*(i - 1)
                if (z(o + 5)**2 + z(o + 6)**2 > s_max) then
                    status = SYMPLECTIC_STEP_OUTSIDE_DOMAIN
                    return
                end if
                if (it == 1) then
                    call darboux_stage_eval(z(o + 5:o + 6), z(o + 3), z(o + 4), &
                                            sigma, mu, ro0, chart(:, i), &
                                            rhs(:, i), fu(:, :, i), fw(:, :, i), &
                                            gu(:, :, i), gw(:, :, i))
                else
                    call darboux_point_eval(z(o + 5:o + 6), z(o + 3), z(o + 4), &
                                            sigma, mu, ro0, rf, kappa1, pth, ham1, &
                                            vpar1, chart(:, i), rhs(:, i), g2, r2)
                end if
            end do
            do i = 1, ns
                o = 6*(i - 1)
                res(o + 1:o + 4) = z(o + 1:o + 4) - w0
                do j = 1, ns
                    res(o + 1:o + 4) = res(o + 1:o + 4) - h*gauss_a(i, j)*rhs(:, j)
                end do
                res(o + 5:o + 6) = chart(:, i) - z(o + 1:o + 2)
            end do
            if (.not. all(is_finite(res(1:n)))) then
                status = SYMPLECTIC_STEP_LINEAR_SOLVE
                return
            end if
            if (it == 1) then
                call stage_jacobian(ns, n, h, fu, fw, gu, gw, jac)
                call rk_lu_factor(n, jac, ipiv, info)
                if (info /= 0) then
                    status = SYMPLECTIC_STEP_LINEAR_SOLVE
                    return
                end if
            end if
            call rk_lu_solve(n, jac, ipiv, res)
            z(1:n) = z(1:n) - res(1:n)
            darboux_stats%newton_iterations = darboux_stats%newton_iterations + 1
            if (all(abs(res(1:n)) <= rtol*tolref(1:n))) then
                converged = .true.
                exit
            end if
        end do
        darboux_stats%max_newton_iterations = &
            max(darboux_stats%max_newton_iterations, it)
        if (.not. converged) then
            status = SYMPLECTIC_STEP_MAXITER
            return
        end if

        w1 = w0
        u1 = u0
        do i = 1, ns
            o = 6*(i - 1)
            w1 = w1 + gauss_d(i)*(z(o + 1:o + 4) - w0)
            u1 = u1 + gauss_d(i)*(z(o + 5:o + 6) - u0)
        end do

        ! End point: Newton for C(u1, phi1, p_phi1) = (X1, Y1). Only an
        ! evaluation whose residual is within tolerance is accepted, so the
        ! returned field data belong to u1.
        do k = 1, MAXIT_ENDPOINT
            if (u1(1)**2 + u1(2)**2 > s_max) then
                status = SYMPLECTIC_STEP_OUTSIDE_DOMAIN
                return
            end if
            call darboux_point_eval(u1, w1(3), w1(4), sigma, mu, ro0, rf, kappa1, &
                                    pth, ham1, vpar1, r2, rhs1, g2, udot1)
            darboux_stats%endpoint_iterations = &
                darboux_stats%endpoint_iterations + 1
            r2 = r2 - w1(1:2)
            if (.not. all(is_finite(r2))) then
                status = SYMPLECTIC_STEP_LINEAR_SOLVE
                return
            end if
            if (all(abs(r2) <= rtol*xy_ref)) then
                if (u1(1)**2 + u1(2)**2 > s_from_radius(sympl_rmax)) &
                    status = SYMPLECTIC_STEP_OUTSIDE_DOMAIN
                return
            end if
            call rk_solve(2, g2, r2, info)
            if (info /= 0) then
                status = SYMPLECTIC_STEP_LINEAR_SOLVE
                return
            end if
            u1 = u1 - r2
        end do
        status = SYMPLECTIC_STEP_MAXITER
    end subroutine darboux_advance

    pure subroutine stage_jacobian(ns, n, h, fu, fw, gu, gw, jac)
        !> Jacobian of the stage residual in the unknowns (W_j, U_j).
        integer, intent(in) :: ns, n
        real(dp), intent(in) :: h, fu(4, 2, MAX_STAGES), fw(4, 2, MAX_STAGES)
        real(dp), intent(in) :: gu(2, 2, MAX_STAGES), gw(2, 2, MAX_STAGES)
        real(dp), intent(out) :: jac(n, n)
        integer :: i, j, k, oi, oj

        jac = 0.0_dp
        do i = 1, ns
            oi = 6*(i - 1)
            do j = 1, ns
                oj = 6*(j - 1)
                jac(oi + 1:oi + 4, oj + 3:oj + 4) = -h*gauss_a(i, j)*fw(:, :, j)
                jac(oi + 1:oi + 4, oj + 5:oj + 6) = -h*gauss_a(i, j)*fu(:, :, j)
            end do
            do k = 1, 4
                jac(oi + k, oi + k) = jac(oi + k, oi + k) + 1.0_dp
            end do
            jac(oi + 5, oi + 1) = -1.0_dp
            jac(oi + 6, oi + 2) = -1.0_dp
            jac(oi + 5:oi + 6, oi + 3:oi + 4) = gw(:, :, i)
            jac(oi + 5:oi + 6, oi + 5:oi + 6) = gu(:, :, i)
        end do
    end subroutine stage_jacobian

    subroutine darboux_step(si, f, status)
        !> One Gauss step of length si%dt from the Darboux state in si. On
        !> success si%z, f (field values, v_par, H, p_theta) and the chart
        !> state hold the end point; on failure both are unchanged.
        type(symplectic_integrator_t), intent(inout) :: si
        type(field_can_t), intent(inout) :: f
        integer, intent(out) :: status
        type(regular_field_t) :: rf
        real(dp) :: w1(4), u1(2), rhs1(4), udot1(2), kappa1, ham1, vpar1
        real(dp) :: theta1, xy_ref, r1

        xy_ref = sqrt(2.0_dp*abs(si%chart_kappa))
        call darboux_advance(si%chart_w, si%chart_u, si%chart_rhs, si%chart_udot, &
                             si%chart_sigma, f%mu, f%ro0, si%dt, si%rtol, xy_ref, &
                             w1, u1, rhs1, udot1, rf, kappa1, ham1, vpar1, status)
        if (status /= SYMPLECTIC_STEP_OK) then
            darboux_stats%failures = darboux_stats%failures + 1
            return
        end if
        if (.not. (kappa1 > 0.0_dp)) then
            status = SYMPLECTIC_STEP_LINEAR_SOLVE
            darboux_stats%failures = darboux_stats%failures + 1
            return
        end if

        theta1 = atan2(u1(2), u1(1))
        theta1 = si%z(2) + modulo(theta1 - si%z(2) + pi, twopi) - pi
        r1 = radius_from_s(u1(1)**2 + u1(2)**2)
        ! s = x**2 + y**2 rounds to 1 - 2**-53 below the boundary; the
        ! boundary event search (locate_symplectic_boundary) converges on an
        ! end point exactly at sympl_rmax, so snap the last few ulp.
        if (abs(r1 - sympl_rmax) <= 4.0_dp*spacing(sympl_rmax)) r1 = sympl_rmax
        si%z = [r1, theta1, w1(3), w1(4)]
        f%Ath = rf%Ath
        f%Aph = rf%Aph
        f%hth = rf%hth
        f%hph = rf%hph
        f%Bmod = rf%Bmod
        f%vpar = vpar1
        f%H = ham1
        f%pth = si%chart_sigma*0.5_dp*(w1(1)**2 + w1(2)**2)
        si%pthold = f%pth

        si%chart_w = w1
        si%chart_u = u1
        si%chart_rhs = rhs1
        si%chart_udot = udot1
        si%chart_kappa = kappa1
        si%chart_z = si%z
        darboux_stats%steps = darboux_stats%steps + 1
    end subroutine darboux_step

    subroutine orbit_timestep_sympl_darboux(si, f, ierr)
        !> si%ntau Gauss steps in the Darboux chart. A step whose end point
        !> lies beyond sympl_rmax returns SYMPLECTIC_STEP_OUTSIDE_DOMAIN for
        !> the boundary wrapper; any failure restores the last accepted state.
        type(symplectic_integrator_t), intent(inout) :: si
        type(field_can_t), intent(inout) :: f
        integer, intent(out) :: ierr

        type(symplectic_integrator_t) :: accepted_integrator
        type(field_can_t) :: accepted_field
        integer :: ktau

        ierr = SYMPLECTIC_STEP_OK
        do ktau = 1, si%ntau
            accepted_integrator = si
            accepted_field = f
            if (.not. chart_current(si, f)) then
                call darboux_encode(si, f, ierr)
                if (ierr /= SYMPLECTIC_STEP_OK) then
                    si = accepted_integrator
                    f = accepted_field
                    return
                end if
            end if
            call darboux_step(si, f, ierr)
            if (ierr /= SYMPLECTIC_STEP_OK) then
                si = accepted_integrator
                f = accepted_field
                return
            end if
        end do
    end subroutine orbit_timestep_sympl_darboux

    pure logical function chart_current(si, f)
        !> The cached Darboux state encodes exactly (si%z, f%mu). Collision
        !> kicks, reseeding and boundary events change z or mu.
        type(symplectic_integrator_t), intent(in) :: si
        type(field_can_t), intent(in) :: f
        integer :: k

        chart_current = .false.
        if (.not. si%chart_valid) return
        if (.not. (abs(f%mu - si%chart_mu) <= 0.0_dp)) return
        do k = 1, 4
            if (.not. (abs(si%z(k) - si%chart_z(k)) <= 0.0_dp)) return
        end do
        chart_current = .true.
    end function chart_current

