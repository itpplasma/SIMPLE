program gen_fo_poly
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_string, only: str_t, str, chars
    use fortsym_print, only: print_expr_sub
    use fortsym_dialect, only: dialect, DIA_FORTRAN
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use fortsym_engine, only: engine_result_t
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    implicit none
    type(arena_t), target::arena
    type(symengine_engine_t)::eng
    type(suite_t)::suite
    type(engine_result_t)::simplified
    type(native_engine_t)::native
    type(expr_t)::x,ci(0:8),basis(0:8),cheby(0:8),raw(0:8),term,coefficient,polynomial
    type(expr_t)::a, b, c, d, e, qv, tt(0:2), pe(0:2), po(0:2), old(10), roots(10)
    type(expr_t)::symbols(40), zero, reconstructed, hvalue, hfirst, hsecond
    type(str_t)::labels(40)
    character(1024)::out
    character(80)::name
    integer::u, n, m, k, r, p, mode, status, ns, second
    call arena%init()
    eng = make_symengine_engine(arena)
    native = make_native_engine(arena)
    call suite_begin(suite, 'Exact SPEC radial polynomial preparation')
    call get_environment_variable('FO_GENERATOR_OUTPUT', out, status=status)
    if (status /= 0) out = 'concept/fo_symplectic_proof/generated'
    ns = 0
    call input('x', x)
    zero = num(arena, 0)
    do n = 0, 8
        write (name, '(a,i0)') 'c', n
        call input(name, ci(n))
    end do
    cheby(0) = num(arena, 1); cheby(1) = x
    do n = 2, 8
        cheby(n) = 2*x*cheby(n - 1) - cheby(n - 2)
    end do
    open (newunit=u, file=trim(out)//'/fo_poly_coeff.inc', status='replace')
    write (u, '(a)') '! Generated by gen/gen_fo_poly.f90 using FortSym. Do not edit.'
    write (u, '(a)') 'if (axis) then', 'select case (m)'
    do mode = 0, 9
        if (mode < 9) then
            m = mode
            write (u, '(a,i0,a)') 'case (', m, ')'
            raw = zero
            raw(m) = x**m
            if (m + 2 <= 8) raw(m + 2) = (m + 2)*x**(m + 2) - (m + 1)*x**m
            do n = m + 4, 8, 2
                raw(n) = num(arena, n)/num(arena, n*n - m*m)* &
                       ((4*(n - 1)*x**2 - num(arena, (n - 2 + m)**2)/num(arena, n - 2) &
                           - num(arena, (n - m)**2)/num(arena, n))*raw(n - 2) &
                          - num(arena, (n - 2)**2 - m*m)/num(arena, n - 2)*raw(n - 4))
            end do
            basis = zero
            do n = m, 8, 2
                polynomial = zero
                do k = 0, (n - m)/2
                    p = n - 2*k
                    coefficient = num(arena, (-1)**k*factorial(n - k))/ &
              num(arena, factorial(k)*factorial((n + m)/2 - k)*factorial((n - m)/2 - k))
                    polynomial = polynomial + coefficient*x**p
                end do
                call check_identity(suite, eng, 'Zernike factorial versus recurrence', &
                                    polynomial - raw(n))
                if (m == 0 .and. n >= 2) polynomial = polynomial - (-1)**(n/2)
      if (m == 1 .and. n >= 3) polynomial = polynomial - (-1)**((n - 1)/2)*((n + 1)/2)*x
                basis(n) = polynomial/num(arena, n + 1)
            end do
        else
            write (u, '(a)') 'end select', 'else'
            basis(0) = num(arena, 1)
            do n = 1, 8
                basis(n) = (cheby(n) - (-1)**n)/num(arena, n + 1)
            end do
        end if
        polynomial = zero
        do n = 0, 8
            polynomial = polynomial + ci(n)*basis(n)
        end do
        term = polynomial
        reconstructed = zero
        do r = 0, 8
     simplified = native%simplify(subs_many(term, [x], [zero])/num(arena, factorial(r)))
            if (.not. simplified%ok) error stop "polynomial simplification failed"
            coefficient = simplified%value
            if (mode < 9) then
                if (r < m .or. mod(r - m, 2) /= 0) then
                    call check_identity(suite, eng, 'structurally zero radial power', &
                                        coefficient)
                end if
            end if
            reconstructed = reconstructed + coefficient*x**r
            write (name, '(a,i0,a)') 'poly(:, :, ', r, ')'
            call emit(trim(name), coefficient, .true.)
            term = diff(term, x)
        end do
        call check_identity(suite, eng, "prepared polynomial equals SPEC basis", &
                            reconstructed - polynomial)
    end do
    write (u, '(a)') 'end if'
    close (u)
    ! One differentiated Horner recurrence, emitted for both requested jet orders.
    call input('a', a); call input('b', b); call input('c', c); call input('d', d)
    do second = 0, 1
        write (name, '(a,i0,a)') '/fo_poly_horner_', second + 1, '.inc'
        open (newunit=u, file=trim(out)//trim(name), status='replace')
       write (u, '(a)') '! Generated by gen/gen_fo_poly.f90 using FortSym. Do not edit.'
        call emit_bound('radial(:, :, 0)', 'poly(:, :, 8)', '0.0_dp', '0.0_dp', a)
        write (u, '(a)') 'radial(:, :, 1:2) = 0.0_dp'
        do n = 7, 0, -1
           if (second == 1) call emit_bound('radial(:, :, 2)', 'x', 'radial(:, :, 2)', &
                                             'radial(:, :, 1)', a*b + 2*c)
            call emit_bound('radial(:, :, 1)', 'x', 'radial(:, :, 1)', &
                            'radial(:, :, 0)', a*b + c)
            write (name, '(a,i0,a)') 'poly(:, :, ', n, ')'
         call emit_bound('radial(:, :, 0)', 'x', 'radial(:, :, 0)', trim(name), a*b + c)
        end do
        close (u)
    end do
    hvalue = ci(8); hfirst = zero; hsecond = zero
    do n = 7, 0, -1
        hsecond = x*hsecond + 2*hfirst
        hfirst = x*hfirst + hvalue
        hvalue = ci(n) + x*hvalue
    end do
    call check_identity(suite, eng, 'Horner first derivative', diff(hvalue, x) - hfirst)
  call check_identity(suite, eng, 'Horner second derivative', diff(hfirst, x) - hsecond)
    ! Angular jets are a linear contraction of the three radial jets.
    call input('cp', a); call input('sp', b); call input('rmi', c); call input('rni', d)
    call input('radial_scale', e)
    do r = 0, 2
        write (name, '(a,i0,a)') 'radial(:, 1, ', r, ')'
        call input(trim(name), pe(r))
        write (name, '(a,i0,a)') 'radial(:, 2, ', r, ')'
        call input(trim(name), po(r))
        tt(r) = pe(r)*a + po(r)*b
    end do
    do n = 1, 10
        write (name, '(a,i0,a)') 'values(:, ', n, ')'
        call input(trim(name), old(n))
    end do
    do second = 0, 1
        roots = old
        roots(1) = old(1) + tt(0)
        roots(2) = old(2) + e*tt(1)
        qv = po(0)*a - pe(0)*b
        roots(3) = old(3) + c*qv
        roots(4) = old(4) - d*qv
        if (second == 1) then
            roots(5) = old(5) + e**2*tt(2)
            qv = po(1)*a - pe(1)*b
            roots(6) = old(6) + c*e*qv
            roots(7) = old(7) - d*e*qv
            roots(8) = old(8) - c**2*tt(0)
            roots(9) = old(9) + c*d*tt(0)
            roots(10) = old(10) - d**2*tt(0)
        end if
        write (name, '(a,i0,a)') '/fo_poly_angular_', second + 1, '.inc'
        open (newunit=u, file=trim(out)//trim(name), status='replace')
       write (u, '(a)') '! Generated by gen/gen_fo_poly.f90 using FortSym. Do not edit.'
        do n = 1, merge(10, 4, second == 1)
            write (name, '(a,i0,a)') 'values(:, ', n, ')'
            call emit(trim(name), roots(n), .false.)
        end do
        close (u)
    end do
    open (newunit=u, file=trim(out)//'/fo_poly_point.inc', status='replace')
    write (u, '(a)') '! Generated by gen/gen_fo_poly.f90 using FortSym. Do not edit.'
    write (u, '(a)') 'if (owner == 1) then'
    call emit_bound('x', 's', '0.0_dp', '0.0_dp', (a + 1)/2)
    call emit_bound('radial_scale', 's', '0.0_dp', '0.0_dp', num(arena, 1)/2)
    write (u, '(a)') 'else'
    call emit_bound('x', 's', '0.0_dp', '0.0_dp', a)
    call emit_bound('radial_scale', 's', '0.0_dp', '0.0_dp', num(arena, 1))
    write (u, '(a)') 'end if'
    close (u)
    call suite_end(suite, trim(out)//'/fo_poly_proof.json')
contains
    integer function factorial(n) result(value)
        integer, intent(in)::n
        integer::i
        value = 1
        do i = 2, n
            value = value*i
        end do
    end function
    subroutine input(name, value)
        character(*), intent(in)::name
        type(expr_t), intent(out)::value
        ns = ns + 1; value = sym(arena, name); symbols(ns) = value; labels(ns) = str(name)
    end subroutine
    subroutine emit(target, value, coefficients)
        character(*), intent(in)::target
        type(expr_t), intent(in)::value
        logical, intent(in)::coefficients
        type(str_t)::bindings(40)
        integer::i
        bindings = labels
        if (coefficients) then
            do i = 0, 8
                write (name, '(a,i0,a)') 'input(:, :, ', i, ')'
                bindings(i + 2) = str(trim(name))
            end do
        end if
        write (u, '(a)') trim(target)//' = '//chars(print_expr_sub(value, &
               dialect(DIA_FORTRAN), symbols(:ns)%id, bindings(:ns), prechecked=.true.))
    end subroutine
    subroutine emit_bound(target, left, right, third, value)
        character(*), intent(in)::target, left, right, third
        type(expr_t), intent(in)::value
        write (u, '(a)') trim(target)//' = '//chars(print_expr_sub(value, &
                                             dialect(DIA_FORTRAN), [a%id, b%id, c%id], &
                                [str(left), str(right), str(third)], prechecked=.true.))
    end subroutine
end program gen_fo_poly
