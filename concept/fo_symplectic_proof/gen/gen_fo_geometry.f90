program gen_fo_geometry
    ! Emit fixed-order Fourier jet contractions, retaining binary operation order.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*)
    use fortsym_string, only: str_t, str, chars
    use fortsym_print, only: print_expr_sub
    use fortsym_dialect, only: dialect, DIA_FORTRAN
    implicit none
    type(arena_t), target :: arena
    type(expr_t) :: a, b
    type(str_t) :: names(2)
    character(1024) :: out
    character(80) :: lhs, rhs1, rhs2
    integer :: u, nord, r, t, z, status

    call arena%init()
    a = sym(arena, 'a')
    b = sym(arena, 'b')
    call get_environment_variable('FO_GENERATOR_OUTPUT', out, status=status)
    if (status /= 0) out = 'concept/fo_symplectic_proof/generated'
    do nord = 2, 3
        write (lhs, '(a,i0,a)') '/fo_geometry_', nord, '.inc'
        open (newunit=u, file=trim(out)//trim(lhs), status='replace')
   write (u, '(a)') '! Generated by gen/gen_fo_geometry.f90 using FortSym. Do not edit.'
        do z = 0, nord
            do t = 0, nord - z
                do r = 0, nord - z - t
                    write (rhs1, '(a,i0,a)') 'coeff(1,', r, ')'
                    write (rhs2, '(a,i0,a)') 'c(', mod(t + z, 4), ')'
                    call emit('jet_c', rhs1, rhs2, a*b)
                    write (rhs1, '(a,i0,a)') 'coeff(2,', r, ')'
                    write (rhs2, '(a,i0,a)') 'c(', mod(t + z + 1, 4), ')'
                    call emit('jet_s', rhs1, rhs2, a*b)
                    call emit('jet_c', 'jet_c', 'jet_s', a - b)
                    write (rhs1, '(a,i0,a,i0,a)') 'angular_factor(', t, ',', z, ',ii)'
                    call emit('jet_c', rhs1, 'jet_c', a*b)
                  write (lhs, '(a,i0,a,i0,a,i0,a)') 'jets(', r, ',', t, ',', z, ',comp)'
                    call emit(lhs, lhs, 'jet_c', a + b)
                end do
            end do
        end do
        close (u)
    end do
    call potential_leaf(.false.)
    call potential_leaf(.true.)
contains
    subroutine potential_leaf(second)
        logical, intent(in) :: second
        if (second) then
            lhs = '/fo_potential_2.inc'
        else
            lhs = '/fo_potential_1.inc'
        end if
        open (newunit=u, file=trim(out)//trim(lhs), status='replace')
   write (u, '(a)') '! Generated by gen/gen_fo_geometry.f90 using FortSym. Do not edit.'
        call emit('pe', 'ce', 'carg', a*b)
        call emit('po', 'co', 'sarg', a*b)
        call emit('pv', 'pe', 'po', a + b)
        call emit('pe', 'co', 'carg', a*b)
        call emit('po', 'ce', 'sarg', a*b)
        call emit('qv', 'pe', 'po', a - b)
        call add('values(:,1)', 'pv', 'tt(0)', .false.)
        call add('values(:,2)', 'pv', 'tt(1)', .false.)
        call emit('pe', 'rmi', 'qv', a*b)
        call add('values(:,3)', 'pe', 'tt(0)', .false.)
        call emit('po', 'rni', 'qv', a*b)
        call add('values(:,4)', 'po', 'tt(0)', .true.)
        if (second) then
            call add('values(:,5)', 'pv', 'tt(2)', .false.)
            call add('values(:,6)', 'pe', 'tt(1)', .false.)
            call add('values(:,7)', 'po', 'tt(1)', .true.)
            call emit('pe', 'rmi', 'rmi', a*b)
            call emit('pe', 'pe', 'pv', a*b)
            call add('values(:,8)', 'pe', 'tt(0)', .true.)
            call emit('pe', 'rmi', 'rni', a*b)
            call emit('pe', 'pe', 'pv', a*b)
            call add('values(:,9)', 'pe', 'tt(0)', .false.)
            call emit('pe', 'rni', 'rni', a*b)
            call emit('pe', 'pe', 'pv', a*b)
            call add('values(:,10)', 'pe', 'tt(0)', .true.)
        end if
        close (u)
    end subroutine potential_leaf

    subroutine add(target, left, right, subtract)
        character(*), intent(in) :: target, left, right
        logical, intent(in) :: subtract
        call emit('increment', left, right, a*b)
        if (subtract) then
            call emit(target, target, 'increment', a - b)
        else
            call emit(target, target, 'increment', a + b)
        end if
    end subroutine add

    subroutine emit(target, left, right, expression)
        character(*), intent(in) :: target, left, right
        type(expr_t), intent(in) :: expression
        names = [str(trim(left)), str(trim(right))]
        write (u, '(a)') trim(target)//' = '// &
            chars(print_expr_sub(expression, dialect(DIA_FORTRAN), &
                                 [a%id, b%id], names, prechecked=.true.))
    end subroutine emit
end program gen_fo_geometry
