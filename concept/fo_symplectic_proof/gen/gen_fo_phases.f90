program gen_fo_phases
    ! Integer Fourier harmonics follow by induction from the addition identities.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, func, sin, cos, &
                            operator(+), operator(-), operator(*)
    use fortsym_string, only: str_t, str, chars
    use fortsym_print, only: print_expr_sub
    use fortsym_dialect, only: dialect, DIA_FORTRAN
    use fortsym_engine_symengine, only: symengine_engine_t, make_symengine_engine
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    use fortsym_fparse, only: parse_fortran_expr
    use fortsym_subs, only: subs_many
    implicit none
    type(arena_t), target :: arena
    type(symengine_engine_t) :: eng
    type(suite_t) :: suite
    type(expr_t) :: a, b, ca, sa, cb, sb, roots(2), parsed
    type(expr_t) :: inputs(4), trig(4), binding(4)
    type(str_t) :: names(4), seed_names(3)
    type(expr_t) :: seed(3)
    character(1024) :: out, filename
    character(:), allocatable :: message
    integer :: u, status, direction, i
    logical :: ok

    call arena%init()
    eng = make_symengine_engine(arena)
    a = sym(arena, 'a')
    b = sym(arena, 'b')
    ca = sym(arena, 'ca')
    sa = sym(arena, 'sa')
    cb = sym(arena, 'cb')
    sb = sym(arena, 'sb')
    inputs = [ca, sa, cb, sb]
    trig = [cos(a), sin(a), cos(b), sin(b)]
    binding = [func('left', [num(arena, 1)]), func('left', [num(arena, 2)]), &
               func('right', [num(arena, 1)]), func('right', [num(arena, 2)])]
    names = [str('left(1)'), str('left(2)'), str('right(1)'), str('right(2)')]
    call get_environment_variable('FO_GENERATOR_OUTPUT', out, status=status)
    if (status /= 0) out = 'concept/fo_symplectic_proof/generated'
    seed = [sym(arena, 'polar_angle'), sym(arena, 'toroidal_angle'), &
            sym(arena, 'stride')]
    seed_names = [str('q(2)'), str('q(3)'), str('real(harmonic_stride, dp)')]
    open (newunit=u, file=trim(out)//'/fo_phase_seed.inc', status='replace')
    write (u, '(a)') &
        '! Generated by gen/gen_fo_phases.f90 using FortSym. Do not edit.', &
        'poloidal(:,0) = [1.0_dp, 0.0_dp]', &
        'toroidal(:,0) = [1.0_dp, 0.0_dp]', &
        'if (harmonic_m > 0) then'
    call seed_output('poloidal(1,1)', cos(seed(1)))
    call seed_output('poloidal(2,1)', sin(seed(1)))
    write (u, '(a)') 'end if', 'if (harmonic_n > 0) then'
    call seed_output('toroidal(1,1)', cos(seed(3)*seed(2)))
    call seed_output('toroidal(2,1)', sin(seed(3)*seed(2)))
    write (u, '(a)') 'end if'
    close (u)
    open (newunit=u, file=trim(out)//'/fo_phase_orders.inc', status='replace')
    write (u, '(a)') &
        '! Generated by gen/gen_fo_phases.f90 using FortSym. Do not edit.', &
        'if (m < 0) then'
    call signed_output('left(2)')
    write (u, '(a)') 'end if', 'if (n < 0) then'
    call signed_output('right(2)')
    write (u, '(a)') 'end if'
    close (u)
    call suite_begin(suite, 'Fourier harmonic exact addition identities')
    do direction = 1, 2
        if (direction == 1) then
            filename = trim(out)//'/fo_phase_sum.inc'
            roots = [ca*cb - sa*sb, sa*cb + ca*sb]
            call check_identity(suite, eng, 'cos addition', &
                                subs_many(roots(1), inputs, trig) - cos(a + b))
            call check_identity(suite, eng, 'sin addition', &
                                subs_many(roots(2), inputs, trig) - sin(a + b))
        else
            filename = trim(out)//'/fo_phase_difference.inc'
            roots = [ca*cb + sa*sb, sa*cb - ca*sb]
            call check_identity(suite, eng, 'cos subtraction', &
                                subs_many(roots(1), inputs, trig) - cos(a - b))
            call check_identity(suite, eng, 'sin subtraction', &
                                subs_many(roots(2), inputs, trig) - sin(a - b))
        end if
        open (newunit=u, file=trim(filename), status='replace')
        write (u, '(a)') &
            '! Generated by gen/gen_fo_phases.f90 using FortSym. Do not edit.'
        do i = 1, 2
            write (u, '(a,i0,a)') 'next(', i, ') = &'
            write (u, '(a)') &
                '    '//chars(print_expr_sub(roots(i), dialect(DIA_FORTRAN), &
                                             [ca%id, sa%id, cb%id, sb%id], names, &
                                             prechecked=.true.))
        end do
        close (u)
        ! Read back the actual array expressions, then prove their trig meaning.
        do i = 1, 2
            if (i == 1) then
                parsed = parse_fortran_expr(arena, trim(filename), &
                                            'next(1)', ok, message)
            else
                parsed = parse_fortran_expr(arena, trim(filename), &
                                            'next(2)', ok, message)
            end if
            if (.not. ok) then
                print *, message
                error stop 'phase readback refused'
            end if
            call check_identity(suite, eng, 'emitted phase polynomial', &
                                parsed - subs_many(roots(i), inputs, binding))
        end do
    end do
    call suite_end(suite, trim(out)//'/fo_phase_proof.json')
contains
    subroutine seed_output(target, expression)
        character(*), intent(in) :: target
        type(expr_t), intent(in) :: expression
        write (u, '(a)') target//' = '// &
            chars(print_expr_sub(expression, dialect(DIA_FORTRAN), &
                                 [seed(1)%id, seed(2)%id, seed(3)%id], &
                                 seed_names, prechecked=.true.))
    end subroutine seed_output

    subroutine signed_output(target)
        character(*), intent(in) :: target
        write (u, '(a)') target//' = '// &
            chars(print_expr_sub(-ca, dialect(DIA_FORTRAN), [ca%id], &
                                 [str(target)], prechecked=.true.))
    end subroutine signed_output
end program gen_fo_phases
