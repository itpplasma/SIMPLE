#!/usr/bin/env python3
"""Consumer physics kernels for local canonical charts; no runtime CAS.

D2 polarization representation Pi1=-mu curl(b)/2, Pi2=0. SymPy supplies
exact differentiation/CSE, not a consumer-owned generic algebra engine.
The particle pullback remains the fortsym-generated D2 implementation.
"""
from pathlib import Path
import argparse
import sympy as s

r, u, mu, th, ph, eps, second = s.symbols(
    'r u mu th ph eps second', real=True)
w = [r, u, mu, th, ph]


def physics(name):
    sheet = name.startswith('sheet')
    curvature = name == 'constant_curvature_on_fieldline'
    if sheet:
        a = s.Integer(1) if name == 'sheet_inner' else s.Rational(13, 10)
        R = 10 + r*s.cos(th)
        C = s.sqrt(100 + 4*a*a*r*r)
        b = s.Matrix([0, 2*a*r/C, 10/C])
        B = C/R
        metric, orientation = [1, r, R], -1
        connection = s.Matrix([0, -b[2]/r, b[1]*s.cos(th)/R])
        # Radial gauge of A_Z=-10 log(R), with A_theta(0)=0.
        # r/10 <= .1 in the certified chart: remainder and its first
        # three derivatives are below double precision (see proof script).
        At = -10*sum((-1)**k*r**(k+2)*s.cos(th)**k /
                    ((k+2)*10**(k+1)) for k in range(20))
        Ap = a*r*r + (s.Rational(-3, 40) if name == 'sheet_outer' else 0)
        A = [At, Ap]
        # Exact radial primitive of curl(b)_r/2, from r=0.
        c = 5/a
        d = s.sqrt(100+c*c*s.cos(th)**2)
        v = r/(s.sqrt(r*r+c*c)+c)
        K = c*s.sin(th)/d*(s.atanh((10*v-c*s.cos(th))/d) -
                            s.atanh(-c*s.cos(th)/d))
    elif curvature:
        metric, orientation = [1, r, 1], 1
        b, B = s.Matrix([0, 1, 0]), s.Integer(1)
        connection = s.zeros(3, 1)
        A, K = [0, -r], s.Integer(0)
    else:
        metric, orientation = [1, 1, 1], 1
        if name == 'magnetic_shear':
            B = s.sqrt(1+s.Rational(4, 25)*r*r)
            b = s.Matrix([0, s.Rational(2, 5)*r/B, 1/B])
            A = [r, -s.Rational(1, 5)*r*r]
        else:
            B = 1+s.Rational(2, 5)*r if name == 'constant_gradient' else s.Integer(1)
            b, A = s.Matrix([0, 0, 1]), [r + (s.Rational(1, 5)*r*r
                if name == 'constant_gradient' else 0), 0]
        connection, K = s.zeros(3, 1), s.Integer(0)
    spatial = [r, th, ph]
    def grad(f):
        return s.Matrix([s.diff(f, q)/h for q, h in zip(spatial, metric)])
    def curl(v):
        return s.Matrix([orientation*(s.diff(metric[k]*v[k], spatial[j]) -
            s.diff(metric[j]*v[j], spatial[k]))/(metric[j]*metric[k])
            for j, k in [(1, 2), (2, 0), (0, 1)]])
    def div(v):
        volume = s.prod(metric)
        return sum(s.diff(volume*v[i]/metric[i], spatial[i])
                   for i in range(3))/volume
    def cross(v, z):
        return orientation*v.cross(z)
    def compact(f):
        return s.factor(s.trigsimp(f)) if sheet else s.simplify(f)
    cb = curl(b).applyfunc(compact)
    kappa = (-cross(b, cb)).applyfunc(compact)
    tau = compact(b.dot(cb))
    db = compact(div(b))
    cr = curl(connection).applyfunc(compact)
    gl = grad(B)/B
    alpha_sq = b.dot(cr)/2 + (tau*tau+db*db)/8
    beta_perp = -tau*tau/2-b.dot(cr)+alpha_sq - cross(b, gl).dot(cross(b, gl)) + b.dot(curl(cross(b, gl)))/2
    beta_par = -2*alpha_sq-3*kappa.dot(gl-kappa)+div(kappa)
    vd = cross(b, mu*grad(B)+u*u*kappa)/B
    H2 = compact(mu*mu*beta_perp/2 + mu*u*u*beta_par/(2*B) -
                 u**4*kappa.dot(kappa)/(2*B*B)-mu*cb.dot(vd)/2)
    rs = connection+cb/2
    # Retain the angular connection after the exact radial phase gauge.
    Rbar = [metric[i]*rs[i]-s.diff(K, spatial[i]) for i in (1, 2)]
    P = s.Matrix([A[i]/eps+u*metric[i+1]*b[i+1]-eps*mu*Rbar[i]
                  for i in range(2)])
    H = u*u/2+mu*B+second*eps*eps*H2
    return P, H, K, rs[0], H2


def emit(name, stream):
    P, H, K, _, H2 = physics(name)
    print(name, 'H2 operations', s.count_ops(H2), flush=True)
    dp = P.jacobian(w)
    hp = [s.hessian(P[i], w) for i in range(2)]
    roots = list(P)+list(dp)+[z for m in hp for z in m]+[H]+list(s.Matrix([H]).jacobian(w))+list(s.hessian(H, w))+[K, H2]
    replacements, reduced = s.cse(roots, symbols=s.numbered_symbols('t'))
    stream.write(f'\ndef {name}(r, u, mu, th, ph, eps, second):\n')
    for v, value in replacements:
        stream.write(f'    {v} = {s.pycode(value)}\n')
    stream.write('    return [\n')
    for value in reduced:
        stream.write(f'        {s.pycode(value)},\n')
    stream.write('    ]\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('output', nargs='?', type=Path, default=Path(__file__).resolve().parents[1]/'build/canonical_kernels.py')
    args = parser.parse_args()
    with args.output.open('w') as stream:
        stream.write('# Generated by gen/derive_canonical.py; do not edit.\nimport math\n')
        for name in ['uniform', 'constant_gradient', 'constant_curvature_on_fieldline', 'magnetic_shear', 'sheet_inner', 'sheet_outer']:
            emit(name, stream)


if __name__ == '__main__':
    main()
