"""Render measured tables from the retained numerical records, not hand values."""
from pathlib import Path
import json
import numpy as np

ROOT = Path("concept/interface_candidates")

def scientific(x):
    return "—" if x is None else f"{x:.2e}"

def label(c):
    name = c["method"]
    if name == "FO":
        return f"FO {c['tol']:.0e}"
    if name in ("C3", "C4"):
        return f"{name}/T{c['order']} d={c['din']}" + (f" h={c['knob']:g}" if name == "C4" else "")
    if name in ("C5", "GL2"):
        return f"{name} w/rho={c['width']:g} h={c['knob']:g}"
    return name

def main():
    rows = json.loads((ROOT / "results/main_summary.json").read_text())
    main_rows = [q for q in rows if q["config"]["sample"] == .5]
    out = ["## Measured comparison", "", f"Completed {len(rows)} configurations × 256 markers. "
           "All tables below are generated by `render_report.py` from the marker records.", "",
           "The complete grid, confidence intervals and distribution metrics are in "
           "[main_summary.csv](results/main_summary.csv) and "
           "[main_summary.json](results/main_summary.json).", "",
           "### Full-orbit statistical convergence", "",
           "Counts are at tolerances 1e-7 / 1e-9 / 1e-11 (the last on strong sheets). "
           "The interval and excursion quantiles refer to the tightest reference. "
           "This grid uses observation dt=0.5; the finer observer below changes "
           "strong T-A from 11 to 12 losses.", "",
           "| Test | a+ | v | Lost counts | Loss, 95% CI | Excursion q10/q50/q90 |",
           "|---|---:|---:|---|---|---|"]
    for case in ("A", "B"):
        for aout in (.3, .75, 2.):
            for speed in (.01, .02, .04):
                q = [q for q in main_rows if q["config"]["method"] == "FO"
                     and q["config"]["case"] == case and q["config"]["aout"] == aout
                     and q["config"]["speed"] == speed and q["config"]["tend"] == 80/speed]
                q.sort(key=lambda q: -q["config"]["tol"])
                if not q:
                    continue
                best = q[-1]
                counts = " / ".join(str(r["lost"]) for r in q)
                ci = best["loss_ci"]
                quantiles = "/".join(f"{r:.4f}" for r in best["excursion_quantiles"])
                out.append(f"| T-{case} | {aout:g} | {speed:g} | {counts} | "
                           f"{best['loss']:.3f} [{ci[0]:.3f},{ci[1]:.3f}] | {quantiles} |")
    for aout, title in ((.75, "moderate"), (2., "strong")):
        out += ["", f"### Candidate comparison: {title} sheet, v=0.02, T=4000", "",
                "E = RMS marker maximum relative energy error; P = RMS maximum "
                "p_varphi error/(R0 v); W1/rho compares the excursion distributions. "
                "Rev = RMS velocity return error/v over valid reversals. "
                "Cost excludes reversals; FO share identifies bands retaining FO.", "",
                "| Test/method | Lost/256 [95% CI] | Failed | E | P | W1/rho | Rev | Cost/FO | FO share |",
                "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for case in ("A", "B"):
            for q in main_rows:
                c = q["config"]
                if c["case"] != case or c["aout"] != aout or c["speed"] != .02 or c["tend"] != 4000:
                    continue
                if c["tol"] != 1e-9:
                    continue
                if c["method"] == "C3" and c["din"] != 3:
                    continue
                if c["method"] == "C4" and c["knob"] != .25:
                    continue
                if c["method"] == "C5" and (c["knob"] != .025 or c["width"] != .2):
                    continue
                if c["method"] == "GL2" and c["knob"] != .025:
                    continue
                ci = q["loss_ci"]
                w = q.get("excursion_wasserstein")
                rev = q["reverse_velocity"]
                out.append(f"| {case}: {label(c)} | {q['lost']} [{ci[0]:.3f},{ci[1]:.3f}] | "
                           f"{q['failed']} | {scientific(q['energy_rms'])} | {scientific(q['pphi_rms'])} | "
                           f"{scientific(w/.02 if w is not None else None)} | {scientific(rev)} | "
                           f"{q['cost_relative']:.2f} | {q['fo_fraction']:.3f} |")
    out += ["", "### Longer return-orbit test: v=0.02, T=16000", "",
            "The earlier grid's short transit horizon can hide phase resets because many "
            "GC exits have no subsequent FO entry. These runs test returns; "
            "mean switches and FO residence are included.", "",
            "| Test/method | Lost/256 | Delta loss [paired 95% CI] | W1/rho | P | Rev(v) | Cost | Switches | FO share |",
            "|---|---:|---|---:|---:|---:|---:|---:|---:|"]
    for q in rows:
        c = q["config"]
        if c["tend"] != 16000 or c["speed"] != .02 or c["tol"] != 1e-9:
            continue
        if c["method"] == "C3" and c["din"] != 3:
            continue
        ci = q.get("loss_delta_ci")
        delta = "—" if ci is None else f"{q['loss_delta']:.4f} [{ci[0]:.4f},{ci[1]:.4f}]"
        w = q.get("excursion_wasserstein")
        out.append(f"| {c['case']}: {label(c)} | {str(q['lost']) + (' (+%d failed)' % q['failed'] if q['failed'] else '')} | {delta} | "
                   f"{scientific(w/.02 if w is not None else None)} | {scientific(q['pphi_rms'])} | "
                   f"{scientific(q['reverse_velocity'])} | {q['cost_relative']:.2f} | "
                   f"{q['switches']:.2f} | {q['fo_fraction']:.3f} |")
    out += ["", "### Excursion uncertainty in the longer return tests", "",
            "Medians and paired mean differences include 95% bootstrap intervals. "
            "Full q10/q50/q90 intervals and Kolmogorov distances are in the JSON summary.", "",
            "| Test/method | Median excursion [95% CI] | Mean excursion difference from FO [95% CI] |",
            "|---|---|---|"]
    for q in rows:
        c = q["config"]
        if c["tend"] != 16000 or c["tol"] != 1e-9 or c["din"] != 3 or q["failed"]:
            continue
        if c["method"] == "C3" and c["order"] != 1:
            continue
        ci = q["excursion_ci"][1]
        delta_ci = q["excursion_delta_ci"]
        out.append(f"| {c['case']}: {label(c)} | {q['excursion_quantiles'][1]:.5f} "
                   f"[{ci[0]:.5f},{ci[1]:.5f}] | {q['excursion_delta']:.2e} "
                   f"[{delta_ci[0]:.2e},{delta_ci[1]:.2e}] |")
    out += ["", "### Radius-observer convergence: strong sheet, v=0.02, T=4000", "",
            "These rows test the loss observer separately from ODE tolerance. "
            "Excursion medians are physical minor-radius ranges.", "",
            "| Test | Observation dt | FO lost | C3/T1 lost | FO median excursion | C3/T1 median excursion |",
            "|---|---:|---:|---:|---:|---:|"]
    for case in ("A", "B"):
        for sample in (.5, .25, .125, .0625, .03125):
            selected = [q for q in rows if q["config"]["case"] == case
                        and q["config"]["aout"] == 2 and q["config"]["speed"] == .02
                        and q["config"]["tend"] == 4000 and q["config"]["sample"] == sample
                        and q["config"]["tol"] == 1e-9 and q["config"]["din"] == 3]
            fo = next((q for q in selected if q["config"]["method"] == "FO"), None)
            gc = next((q for q in selected if q["config"]["method"] == "C3"
                       and q["config"]["order"] == 1), None)
            if fo is not None and gc is not None:
                out.append(f"| {case} | {sample:g} | {fo['lost']} | {gc['lost']} | "
                           f"{fo['excursion_quantiles'][1]:.6f} | {gc['excursion_quantiles'][1]:.6f} |")
    out += ["", "### Negative-control tolerance checks: strong sheet, v=0.02, T=4000", "",
            "Counts at RK tolerance 1e-7 / 1e-9 / 1e-11. "
            "A solver-converged count cannot repair missing sheet or phase physics.", "",
            "| Test/method | Lost counts | Failed counts | Velocity return RMS at 1e-11 |",
            "|---|---|---|---:|"]
    for case in ("A", "B"):
        for method in ("C1L0", "C1L1", "C2fixed", "C2pphi", "C3"):
            selected = [q for q in rows if q["config"]["case"] == case
                        and q["config"]["aout"] == 2 and q["config"]["speed"] == .02
                        and q["config"]["tend"] == 4000 and q["config"]["sample"] == .5
                        and q["config"]["din"] == 3 and q["config"]["method"] == method
                        and q["config"]["order"] == 0]
            selected.sort(key=lambda q: -q["config"]["tol"])
            if len(selected) == 3:
                losses = "/".join(str(q["lost"]) for q in selected)
                failed = "/".join(str(q["failed"]) for q in selected)
                out.append(f"| {case}: {'C3/T0' if method=='C3' else method} | {losses} | "
                           f"{failed} | {scientific(selected[-1]['reverse_velocity'])} |")
    out += ["", "Rows with failures require the loss bounds in the JSON summary; "
            "their distributions are deliberately omitted. Statistical agreement at a "
            "wide band can simply mean almost all the trajectory used FO.", "",
            "### Measured epsilon exponents", "",
            "Fits use three radii at fixed gyrotime T=50. C1 slopes are conditional "
            "on its valid markers; C2 starts in the outer smooth volume to exercise "
            "discarding phase. C4/C5 start next to the strong sheet. Values near zero "
            "for C1/C2 describe finite normalized phase-space error, not a convergence order.", "",
            "| Candidate | T-A p(position/rho), p(velocity/v) | T-B p(position/rho), p(velocity/v) |",
            "|---|---:|---:|"]
    acc = np.genfromtxt(ROOT / "results/accuracy.csv", names=True, delimiter=",", dtype=None, encoding="utf8")
    sheet = np.genfromtxt(ROOT / "results/sheet_accuracy.csv", names=True, delimiter=",", dtype=None, encoding="utf8")
    for method, order in (("GC", 0), ("GC", 1), ("C1L0", None), ("C1L1", None),
                          ("C2fixed", None), ("C2pphi", None), ("C4", None), ("C5", None)):
        values = []
        for case in (1, 2):
            x = acc if method == "GC" else sheet
            use = (x["case"] == case) & (x["method"] == method)
            if method == "GC":
                use &= x["order"] == order
            a = x[use]
            if len(a) < 3:
                values.append("—")
            else:
                p = [np.polyfit(np.log(a["speed"]), np.log(a[col]), 1)[0]
                     for col in ("position_rms", "velocity_rms")]
                values.append(f"{p[0]:.3f}, {p[1]:.3f}")
        out.append(f"| {'C3/T'+str(order) if method == 'GC' else method} | {values[0]} | {values[1]} |")
    out += ["", "Negative C5 slopes at fixed w/rho and fixed gyro step do not establish "
            "a sharp-target order; its phase-space error is about 1% here and does not "
            "vanish with decreasing rho at these fixed layer parameters.", ""]
    (ROOT / "results/report_tables.md").write_text("\n".join(out))

    scans = ["# Parameter scans", "", "Generated from main_summary.json. "
             "Loss differences use the tightest same-grid FO reference; cost uses FO 1e-9.", "",
             "| Test | a+ | v | Method/parameters | Lost | Delta loss [paired 95% CI] | W1/rho | "
             "E | P | Rev(v) | Cost | Switches | FO share |",
             "|---|---:|---:|---|---:|---|---:|---:|---:|---:|---:|---:|---:|"]
    for q in rows:
        c = q["config"]
        if c["method"] not in ("C3", "C4", "C5", "GL2"):
            continue
        ci = q.get("loss_delta_ci")
        delta = "—" if ci is None else f"{q['loss_delta']:.4f} [{ci[0]:.4f},{ci[1]:.4f}]"
        w = q.get("excursion_wasserstein")
        method = label(c)+f" tol={c['tol']:.0e} sample={c['sample']:g}"
        scans.append(f"| {c['case']} | {c['aout']:g} | {c['speed']:g} | {method} | "
                     f"{q['lost']} | {delta} | {scientific(w/c['speed'] if w is not None else None)} | "
                     f"{scientific(q['energy_rms'])} | {scientific(q['pphi_rms'])} | "
                     f"{scientific(q['reverse_velocity'])} | {q['cost_relative']:.2f} | "
                     f"{q['switches']:.2f} | {q['fo_fraction']:.3f} |")
    (ROOT / "results/parameter_scans.md").write_text("\n".join(scans)+"\n")
    readme = (ROOT / "README.md").read_text()
    start, rest = readme.split("<!-- MEASURED_RESULTS -->")
    old, finish = rest.split("<!-- END_MEASURED_RESULTS -->")
    (ROOT / "README.md").write_text(start+"<!-- MEASURED_RESULTS -->\n"+"\n".join(out)
                                   +"\n<!-- END_MEASURED_RESULTS -->"+finish)

if __name__ == "__main__":
    main()
