"""Generate sharp-volume torsion gradient; no differentiated sheet step."""
from pathlib import Path
import sympy as s
R,Z,phi,R0,F,a,d,n=s.symbols('rr zz phi r0 f a d n',real=True)
w=R-R0
K=-w*s.sin(n*phi)+Z*s.cos(n*phi)
B=s.Matrix([-2*a*Z/R+d*n*Z*K/R,F/R-d*K,2*a*w/R-d*n*w*K/R])
C=s.Matrix([s.diff(B[2],phi)/R-s.diff(B[1],Z),s.diff(B[0],Z)-s.diff(B[2],R),(s.diff(R*B[1],R)-s.diff(B[0],phi))/R])
N=s.factor(B.dot(C));D=s.factor(B.dot(B))
res=[s.diff(N,q)/D-N*s.diff(D,q)/D**2 for q in (R,phi,Z)]
subs,expr=s.cse(res, symbols=s.numbered_symbols('w'))
lines=['! Generated by proofs/generate_torsion.py (SymPy).',
       'subroutine torsion_gradient(rr, zz, phi, r0, f, a, d, n, grad)',
       '    real(dp), intent(in) :: rr, zz, phi, r0, f, a, d, n',
       '    real(dp), intent(out) :: grad(3)']
for start in range(0,len(subs),6):
 lines.append('    real(dp) :: '+', '.join(str(v) for v,e in subs[start:start+6]))
for v,e in subs:
 lines += ['    '+q for q in s.fcode(e,assign_to=str(v),source_format='free',standard=2008).splitlines()]
for i,e in enumerate(expr):
 lines += ['    '+q for q in s.fcode(e,assign_to=f'grad({i+1})',source_format='free',standard=2008).splitlines()]
lines.append('end subroutine')
Path('concept/interface_candidates/torsion_kernel.inc').write_text('\n'.join(lines)+'\n')
print('Generated torsion gradient:',len(subs),'temporaries')
