program generate_orbit_systems
    ! Residuals and Newton Jacobians of the implicit symplectic guiding-centre
    ! schemes from one symbolic statement each. Every field quantity is an
    ! opaque applied function of the stage state; its partial derivatives bind
    ! to the members of field_can_t, and each Jacobian is the symbolic
    ! derivative of its residual. The same file states v_par, H and p_theta
    ! once and generates their derivatives up to second order, and the
    ! guiding-centre rates of a Boozer field for OpenACC.
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, func, func_in, operator(+), &
                            operator(-), operator(*), operator(/), operator(**), &
                            sqrt
    use fortsym_diff, only: diff, partial_derivative
    use fortsym_subs, only: subs_many
    use fortsym_chain, only: chain_t, fold_numbers
    use fortsym_kernel, only: kernel_spec_t, kernel_binding_t, emit_kernel, &
                              KERNEL_SUBROUTINE
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_fortran_kernel_ir, &
                                   emit_cuda_device_ir, TARGET_FORTRAN_OPENACC, &
                                   TARGET_CUDA
    use fortgen_horner_emit, only: horner_kernel_spec_t, emit_horner_kernel
    use fortgen_kernel_target, only: HORNER_CUDA => TARGET_CUDA
    use fortgen_string, only: fg_str => str, fg_chars => chars
    use fortsym_string, only: str_t, str, chars
    implicit none

    type :: stage_t
        type(expr_t) :: H, pth, vpar, hth, hph
    end type stage_t

    type(arena_t), target :: arena
    type(kernel_binding_t), allocatable :: bindings(:)
    logical :: first_in_file
    character(4096) :: output_dir
    character(256) :: fortsym_revision
    integer :: unit, s

    output_dir = 'src/generated'
    if (command_argument_count() > 0) call get_command_argument(1, output_dir)
    fortsym_revision = ''
    if (command_argument_count() > 1) call get_command_argument(2, fortsym_revision)
    call arena%init()

    ! The kernels go to include files so that the OpenACC steps can compile
    ! the Euler and midpoint kernels in their own scope.
    open (newunit=unit, file=trim(output_dir)//'/orbit_systems_midpoint.inc', &
          status='replace', action='write')
    first_in_file = .true.
    call emit_midpoint(unit)
    close (unit)

    open (newunit=unit, file=trim(output_dir)//'/orbit_systems_euler1.inc', &
          status='replace', action='write')
    first_in_file = .true.
    call emit_euler1(unit)
    close (unit)

    open (newunit=unit, file=trim(output_dir)//'/orbit_systems_kernels.inc', &
          status='replace', action='write')
    first_in_file = .true.
    call emit_euler2(unit)
    do s = 1, 4
        call emit_gauss(unit, s)
    end do
    call emit_lobatto(unit, 3)
    call emit_rates_canonical(unit)
    close (unit)

    open (newunit=unit, file=trim(output_dir)//'/gpu_derivatives2_radial_mixed.inc', &
          status='replace', action='write')
    first_in_file = .true.
    call emit_field_derivatives(unit, 'gpu_radial_mixed_second_derivatives', 2, .true.)
    close (unit)

    call emit_rates_boozer(output_dir)
    call emit_cuda_euler1_boozer(output_dir)

    open (newunit=unit, file=trim(output_dir)//'/orbit_systems_generated.f90', &
          status='replace', action='write')
    write (unit, '(a)') 'module orbit_systems_generated'
   write (unit, '(a)') '    ! Generated by gen/generate_orbit_systems.f90. Do not edit.'
    write (unit, '(a)') '    use field_can_base, only: field_can_t'
    write (unit, '(a)') '    implicit none'
    write (unit, '(a)') 'contains'
    write (unit, '(a)') "    include 'orbit_systems_euler1.inc'"
    write (unit, '(a)') "    include 'orbit_systems_midpoint.inc'"
    write (unit, '(a)') "    include 'orbit_systems_kernels.inc'"
    write (unit, '(a)') 'end module orbit_systems_generated'
    close (unit)

contains

    function x(i) result(e)
        integer, intent(in) :: i
        type(expr_t) :: e
        e = sym(arena, 'x('//itoa(i)//')')
    end function x

    function z(i) result(e)
        integer, intent(in) :: i
        type(expr_t) :: e
        e = sym(arena, 'z('//itoa(i)//')')
    end function z

    function coeff(name, k, l) result(e)
        character(*), intent(in) :: name
        integer, intent(in) :: k, l
        type(expr_t) :: e
        e = sym(arena, name//'('//itoa(k)//', '//itoa(l)//')')
    end function coeff

    function itoa(i) result(text)
        integer, intent(in) :: i
        character(:), allocatable :: text
        character(16) :: buffer
        write (buffer, '(i0)') i
        text = trim(buffer)
    end function itoa

    !> Field quantities of field_can_t variable `field` at the state
    !> (r, th, ph, pph); registers their bindings.
    function stage(field, r, th, ph, pph) result(q)
        character(*), intent(in) :: field
        type(expr_t), intent(in) :: r, th, ph, pph
        type(stage_t) :: q
        type(expr_t) :: args4(4), args3(3)

        args4 = [r, th, ph, pph]
        args3 = [r, th, ph]
        q%H = func('H_'//tag(field), args4)
        q%pth = func('pth_'//tag(field), args4)
        q%vpar = func('vpar_'//tag(field), args4)
        q%hth = func('hth_'//tag(field), args3)
        q%hph = func('hph_'//tag(field), args3)
        call bind_quantity('H_'//tag(field), field//'%', 'H', 4)
        call bind_quantity('pth_'//tag(field), field//'%', 'pth', 4)
        call bind_quantity('vpar_'//tag(field), field//'%', 'vpar', 4)
        call bind_quantity('hth_'//tag(field), field//'%', 'hth', 3)
        call bind_quantity('hph_'//tag(field), field//'%', 'hph', 3)
    end function stage

    function tag(field) result(text)
        character(*), intent(in) :: field
        character(:), allocatable :: text
        integer :: k
        text = ''
        do k = 1, len(field)
            select case (field(k:k))
            case ('a':'z', 'A':'Z', '0':'9')
                text = text//field(k:k)
            end select
        end do
    end function tag

    !> Value, gradient and packed Hessian of one field_can_t quantity. The
    !> Hessian packing is that of get_derivatives2.
    subroutine bind_quantity(head, prefix, name, nargs)
        character(*), intent(in) :: head, prefix, name
        integer, intent(in) :: nargs
        integer :: i, j

        call add_binding(head, [integer ::], prefix//name)
        do i = 1, nargs
            call add_binding(head, [i], prefix//'d'//name//'('//itoa(i)//')')
            do j = i, nargs
                call add_binding(head, [i, j], &
                                 prefix//'d2'//name//'('//itoa(packed(i, j))//')')
            end do
        end do
    end subroutine bind_quantity

    pure integer function packed(i, j)
        integer, intent(in) :: i, j
        integer, parameter :: table(4, 4) = reshape([1, 2, 3, 7, 2, 4, 5, 8, &
                                                     3, 5, 6, 9, 7, 8, 9, 10], [4, 4])
        packed = table(i, j)
    end function packed

    subroutine add_binding(head, indices, replacement)
        character(*), intent(in) :: head, replacement
        integer, intent(in) :: indices(:)
        type(kernel_binding_t) :: b

        b%head = str(head)
        if (size(indices) > 0) b%derivative_indices = indices
        b%replacement = str(replacement)
        if (.not. allocated(bindings)) allocate (bindings(0))
        bindings = [bindings, b]
    end subroutine add_binding

    function d(q, i) result(e)
        type(expr_t), intent(in) :: q
        integer, intent(in) :: i
        type(expr_t) :: e
        e = partial_derivative(q, i)
    end function d

    !> Canonical poloidal momentum rate, H' = dH/dr / dp_theta/dr and the
    !> rates of the guiding-centre equations at one stage.
    function hprime(q) result(e)
        type(stage_t), intent(in) :: q
        type(expr_t) :: e
        e = d(q%H, 1)/d(q%pth, 1)
    end function hprime

    function pthdot(q) result(e)
        type(stage_t), intent(in) :: q
        type(expr_t) :: e
        e = -(d(q%H, 2) - hprime(q)*d(q%pth, 2))
    end function pthdot

    function phdot(q) result(e)
        type(stage_t), intent(in) :: q
        type(expr_t) :: e
        e = (q%vpar - hprime(q)*q%hth)/q%hph
    end function phdot

    function pphdot(q) result(e)
        type(stage_t), intent(in) :: q
        type(expr_t) :: e
        e = -(d(q%H, 3) - hprime(q)*d(q%pth, 3))
    end function pphdot

    !> Guiding-centre rates (r, theta, phi, p_phi) in canonical coordinates.
    !> Every RHS of the explicit integrators derives from this statement.
    function gc_rates(q, dH, dpth) result(rates)
        type(stage_t), intent(in) :: q
        type(expr_t), intent(in) :: dH(3), dpth(3)
        type(expr_t) :: rates(4), hp

        hp = dH(1)/dpth(1)
        rates(1) = -(dH(2) - q%hth/q%hph*dH(3))/dpth(1)
        rates(2) = hp
        rates(3) = (q%vpar - hp*q%hth)/q%hph
        rates(4) = -(dH(3) - hp*dpth(3))
    end function gc_rates

    subroutine emit_rates_canonical(unit)
        integer, intent(in) :: unit
        type(stage_t) :: f
        type(expr_t) :: rates(4)
        type(str_t), allocatable :: refs(:)
        integer :: i

        call reset()
        f = stage('f', sym(arena, 'r_'), sym(arena, 'th_'), sym(arena, 'ph_'), &
                  sym(arena, 'pph_'))
        rates = gc_rates(f, [d(f%H, 1), d(f%H, 2), d(f%H, 3)], &
                         [d(f%pth, 1), d(f%pth, 2), d(f%pth, 3)])
        allocate (refs(4))
        do i = 1, 4
            refs(i) = str('zdot('//itoa(i)//')')
        end do
        call emit_one(unit, 'gc_rates_canonical', rates, refs, 'zdot', '(4)', &
                      ['f'], [character(6) ::], [character(6) ::])
    end subroutine emit_rates_canonical

    subroutine emit_euler1(unit)
        integer, intent(in) :: unit
        type(stage_t) :: f
        type(expr_t) :: res(2), dt, pthold

        call reset()
        dt = sym(arena, 'dt')
        pthold = sym(arena, 'pthold')
        f = stage('f', x(1), z(2), z(3), x(2))
        res = euler1_residual(f%pth, [d(f%H, 1), d(f%H, 2), d(f%H, 3)], &
                              [d(f%pth, 1), d(f%pth, 2), d(f%pth, 3)], x(2), z(4), &
                              pthold, dt)
        call emit_pair(unit, 'euler1', res, 2, ['f'], &
                       [character(6) :: 'dt', 'pthold', 'z', 'x'], ['(4)', '(2)'])
    end subroutine emit_euler1

    !> Explicit-implicit Euler residual (Newton unknowns r and p_phi at fixed
    !> angles) from p_theta and the gradients of H and p_theta at the new
    !> state; the Fortran and CUDA kernels share this statement.
    function euler1_residual(pth, dh, dpth, pph, pph_old, pthold, dt) result(res)
        type(expr_t), intent(in) :: pth, dh(3), dpth(3), pph, pph_old, pthold, dt
        type(expr_t) :: res(2)

        res(1) = dpth(1)*(pth - pthold) + dt*(dh(2)*dpth(1) - dh(1)*dpth(2))
        res(2) = dpth(1)*(pph - pph_old) + dt*(dh(3)*dpth(1) - dh(1)*dpth(3))
    end function euler1_residual

    subroutine emit_euler2(unit)
        integer, intent(in) :: unit
        type(stage_t) :: f
        type(expr_t) :: res(3), dt, pthold

        call reset()
        dt = sym(arena, 'dt')
        pthold = sym(arena, 'pthold')
        f = stage('f', x(1), x(2), x(3), z(4))
        res(1) = f%pth - pthold
        res(2) = d(f%pth, 1)*(x(2) - z(2)) - dt*d(f%H, 1)
        res(3) = d(f%pth, 1)*f%hph*(x(3) - z(3)) &
                 - dt*(d(f%pth, 1)*f%vpar - d(f%H, 1)*f%hth)
        call emit_pair(unit, 'euler2', res, 3, ['f'], &
                       [character(6) :: 'dt', 'pthold', 'z', 'x'], ['(4)', '(3)'])
    end subroutine emit_euler2

    subroutine emit_midpoint(unit)
        ! x = (r, theta, phi, p_phi) at the end point and r at the midpoint.
        integer, intent(in) :: unit
        type(stage_t) :: fm, fe
        type(expr_t) :: res(5), dt, pthold, half, pthdotbar, mid(4)
        integer :: i

        call reset()
        dt = sym(arena, 'dt')
        pthold = sym(arena, 'pthold')
        half = num(arena, 1)/num(arena, 2)
        ! The midpoint angles and momentum, (x + z)/2, enter as symbols of
        ! their own so that the chain-rule factor 1/2 multiplies each
        ! midpoint derivative once.
        do i = 2, 4
            mid(i) = sym(arena, 'mid'//itoa(i))
        end do
        fm = stage('fmid', x(5), mid(2), mid(3), mid(4))
        fe = stage('fend', x(1), x(2), x(3), x(4))
        pthdotbar = d(fm%pth, 1)*d(fm%H, 2) - d(fm%pth, 2)*d(fm%H, 1)
        res(1) = d(fm%pth, 1)*(fe%pth - pthold) + dt*pthdotbar
        res(2) = d(fm%pth, 1)*(x(2) - z(2)) - dt*d(fm%H, 1)
        res(3) = d(fm%pth, 1)*fm%hph*(x(3) - z(3)) &
                 - dt*(d(fm%pth, 1)*fm%vpar - d(fm%H, 1)*fm%hth)
        res(4) = d(fm%pth, 1)*(x(4) - z(4)) &
                 + dt*(d(fm%H, 3)*d(fm%pth, 1) - d(fm%H, 1)*d(fm%pth, 3))
        res(5) = d(fm%pth, 1)*(fm%pth - pthold) + half*dt*pthdotbar
        mid(1) = num(arena, 0)
        call emit_pair(unit, 'midpoint', res, 5, [character(4) :: 'fmid', 'fend'], &
                       [character(6) :: 'dt', 'pthold', 'z', 'x'], ['(4)', '(5)'], &
                       mid=mid, mid_factor=half)
    end subroutine emit_midpoint

    subroutine emit_gauss(unit, s)
        ! x(4k-3:4k) = (r, theta, phi, p_phi) at stage k.
        integer, intent(in) :: unit, s
        type(stage_t) :: f(s)
        type(expr_t) :: res(4*s), dt, pthold, h
        integer :: k, l

        call reset()
        dt = sym(arena, 'dt')
        pthold = sym(arena, 'pthold')
        do k = 1, s
            f(k) = stage('fs('//itoa(k)//')', x(4*k - 3), x(4*k - 2), &
                         x(4*k - 1), x(4*k))
        end do
        do k = 1, s
            res(4*k - 3) = f(k)%pth - pthold
            res(4*k - 2) = x(4*k - 2) - z(2)
            res(4*k - 1) = x(4*k - 1) - z(3)
            res(4*k) = x(4*k) - z(4)
            do l = 1, s
                h = dt*coeff('a', k, l)
                res(4*k - 3) = res(4*k - 3) - h*pthdot(f(l))
                res(4*k - 2) = res(4*k - 2) - h*hprime(f(l))
                res(4*k - 1) = res(4*k - 1) - h*phdot(f(l))
                res(4*k) = res(4*k) - h*pphdot(f(l))
            end do
        end do
        call emit_pair(unit, 'gauss'//itoa(s), res, 4*s, ['fs'], &
                       [character(6) :: 'dt', 'pthold', 'z', 'a', 'x'], &
                       [character(16) :: '(4)', '('//itoa(s)//', '//itoa(s)//')', &
                        '('//itoa(4*s)//')'], &
                       stages=s)
    end subroutine emit_gauss

    subroutine emit_lobatto(unit, s)
        ! Lobatto IIIA-IIIB: x(1:2) = (r, p_phi) at the first stage, whose
        ! angles are those of z; x(4k-5:4k-2) = (r, theta, phi, p_phi) at
        ! stage k >= 2.
        integer, intent(in) :: unit, s
        type(stage_t) :: f(s)
        type(expr_t) :: res(4*s - 2), dt, pthold, h, hhat
        integer :: k, l, m

        call reset()
        dt = sym(arena, 'dt')
        pthold = sym(arena, 'pthold')
        f(1) = stage('fs(1)', x(1), z(2), z(3), x(2))
        do k = 2, s
            m = 4*k - 2
            f(k) = stage('fs('//itoa(k)//')', x(m - 3), x(m - 2), x(m - 1), x(m))
        end do
        res(1) = f(1)%pth - pthold
        res(2) = x(2) - z(4)
        do l = 1, s
            hhat = dt*coeff('ahat', 1, l)
            res(1) = res(1) - hhat*pthdot(f(l))
            res(2) = res(2) - hhat*pphdot(f(l))
        end do
        do k = 2, s
            m = 4*k - 2
            res(m - 3) = f(k)%pth - pthold
            res(m - 2) = x(m - 2) - z(2)
            res(m - 1) = x(m - 1) - z(3)
            res(m) = x(m) - z(4)
            do l = 1, s
                h = dt*coeff('a', k, l)
                hhat = dt*coeff('ahat', k, l)
                res(m - 3) = res(m - 3) - hhat*pthdot(f(l))
                res(m - 2) = res(m - 2) - h*hprime(f(l))
                res(m - 1) = res(m - 1) - h*phdot(f(l))
                res(m) = res(m) - hhat*pphdot(f(l))
            end do
        end do
        call emit_pair(unit, 'lobatto'//itoa(s), res, 4*s - 2, ['fs'], &
                       [character(6) :: 'dt', 'pthold', 'z', 'a', 'ahat', 'x'], &
                       [character(16) :: '(4)', '('//itoa(s)//', '//itoa(s)//')', &
                        '('//itoa(s)//', '//itoa(s)//')', '('//itoa(4*s - 2)//')'], &
                       stages=s)
    end subroutine emit_lobatto

    !> v_par, H and p_theta of field_can_t at (r, theta, phi, p_phi) and their
    !> derivatives through `order`. v_par = (p_phi - A_phi/ro0)/h_phi is a
    !> named intermediate, so every derivative reuses v_par and the lower
    !> derivatives of v_par instead of re-expanding it. `radial_mixed` emits
    !> only the second derivatives with a radial or p_phi index, which the
    !> two-variable Euler Newton system reads, from the values and gradients
    !> that get_derivatives already stored in f, and drops d2Phie: SIMPLE's
    !> electric potential is linear in s. Reading them back from f, as the
    !> hand-written device code did, keeps the OpenACC Euler kernel at its
    !> register count.
    subroutine emit_field_derivatives(unit, name, order, radial_mixed)
        integer, intent(in) :: unit, order
        character(*), intent(in) :: name
        logical, intent(in) :: radial_mixed
        character(4), parameter :: quantity(3) = ['vpar', 'H   ', 'pth ']
        type(chain_t) :: c
        type(expr_t) :: x(4), aph, ath, hth, hph, bmod, phie, mu, ro0, q(3), e
        type(expr_t), allocatable :: roots(:), old(:), new(:), defs(:)
        type(str_t), allocatable :: refs(:)
        integer, allocatable :: needed(:)
        logical, allocatable :: keep(:)
        integer :: i, j, m, k

        call reset()
        x = [sym(arena, 'r_'), sym(arena, 'th_'), sym(arena, 'ph_'), sym(arena, 'pphi')]
        aph = field_function('Aph', x(1:3))
        ath = field_function('Ath', x(1:3))
        hth = field_function('hth', x(1:3))
        hph = field_function('hph', x(1:3))
        bmod = field_function('Bmod', x(1:3))
        phie = field_function('Phie', x(1:3))
        mu = func_in(arena, 'mu')
        ro0 = func_in(arena, 'ro0')
        call add_binding('mu', [integer ::], 'f%mu')
        call add_binding('ro0', [integer ::], 'f%ro0')

        call c%init(x)
        call gc_quantities(c, x(4), aph, ath, hth, hph, bmod, phie, mu, ro0, &
                           q(1), q(2), q(3))
        allocate (roots(0), refs(0))
        do m = 1, 3
            call add_root(roots, refs, q(m), 'f%'//trim(quantity(m)))
        end do
        if (order >= 1 .and. .not. radial_mixed) then
            do m = 1, 3
                do i = 1, 4
                    call add_root(roots, refs, c%d(q(m), i), &
                                  'f%d'//trim(quantity(m))//'('//itoa(i)//')')
                end do
            end do
        end if
        if (order >= 2) then
            do m = 1, 3
                do i = 1, 4
                    do j = i, 4
                        if (i == 4 .and. j == 4) cycle
                        if (radial_mixed .and. i /= 1 .and. j /= 4) cycle
                        e = c%d(c%d(q(m), i), j)
                        call add_root(roots, refs, e, 'f%d2'//trim(quantity(m))//'('// &
                                      itoa(packed(i, j))//')')
                    end do
                end do
            end do
        end if
        if (radial_mixed) then
            ! Values and gradients come from f; the first three roots are
            ! the values themselves and are not assigned again.
            roots = roots(4:)
            refs = refs(4:)
            allocate (old(0), new(0))
            do i = 1, 3
                do j = i, 3
                    old = [old, partial_derivative(partial_derivative(phie, i), j)]
                    new = [new, num(arena, 0)]
                end do
            end do
            old = [old, q(1)]
            new = [new, stored('vpar_f', 'f%vpar')]
            do i = 1, 4
                e = c%d(q(1), i)
                if (c%index_of(e) == 0) cycle
                old = [old, e]
                new = [new, stored('dvpar_f'//itoa(i), 'f%dvpar('//itoa(i)//')')]
            end do
            do k = 1, size(roots)
                roots(k) = fold_numbers(subs_many(roots(k), old, new))
            end do
            needed = c%needed(roots)
            keep = [(.not. any(old%id == c%names(needed(k))%id), k=1, size(needed))]
            needed = pack(needed, keep)
            allocate (defs(size(needed)))
            do k = 1, size(needed)
                defs(k) = fold_numbers(subs_many(c%defs(needed(k)), old, new))
            end do
            call emit_with_locals(unit, name, c, needed, roots, refs, defs)
            return
        end if
        needed = c%needed(roots)
        call emit_with_locals(unit, name, c, needed, roots, refs, c%defs(needed))
    end subroutine emit_field_derivatives

    !> v_par = (p_phi - A_phi/ro0)/h_phi as a named intermediate of chain c,
    !> H = v_par^2/2 + mu B + Phi_e and p_theta = h_theta v_par + A_theta/ro0.
    subroutine gc_quantities(c, pph, aph, ath, hth, hph, bmod, phie, mu, ro0, &
                             vpar, h, pth)
        type(chain_t), intent(inout) :: c
        type(expr_t), intent(in) :: pph, aph, ath, hth, hph, bmod, phie, mu, ro0
        type(expr_t), intent(out) :: vpar, h, pth

        vpar = c%let('vpar', (pph - aph/ro0)/hph)
        h = vpar**2/2 + mu*bmod + phie
        pth = hth*vpar + ath/ro0
    end subroutine gc_quantities

    !> A value that an earlier kernel stored in field_can_t: an opaque
    !> application bound to its member.
    function stored(head, member) result(e)
        character(*), intent(in) :: head, member
