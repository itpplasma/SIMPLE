        else
            spec%args = [str('f')]
            spec%arg_types = [str('type(field_can_t)')]
            spec%arg_intents = [str('inout')]
        end if
        allocate (spec%outputs(0))
        spec%locals = [(c%names(needed(k))%name(), k=1, size(needed))]
